"""
ASTRAEUS Follow-Up Queue Manager & Boundary Authorization Service.
Enforces deterministic gate authority at the physical telescope scheduling boundary.
Agents submit investigation proposals; only verified deterministic gate outcomes
can authorize queue insertion.
"""

from typing import Dict, Any, List, Optional
from datetime import datetime, timezone
import hashlib
import json
import copy
from pydantic import BaseModel, Field, ConfigDict, model_validator

from astraeus_agents.contracts import (
    TerminalInvestigationStatus,
    SkepticChallenge,
    ChallengeStatus,
)
from astraeus_agents.evidence_gates import DeterministicEvidenceGateEngine, GateEvaluationResult
from astraeus_agents.dossier import InvestigationDossier


class UnauthorizedQueueSubmissionError(PermissionError):
    """Raised when an agent or unauthorized caller attempts to write directly to the follow-up queue."""
    pass


class GateValidationMismatchError(ValueError):
    """Raised when a dossier or proposal attempts to claim follow-up without meeting gate criteria."""
    pass


class TamperDetectionError(RuntimeError):
    """Raised when record digests or gate parameters indicate downstream data tampering."""
    pass


class InvestigationProposal(BaseModel):
    """
    Candidate follow-up proposal generated by agents or orchestrator.
    Proposals have zero execution authority until evaluated by the Gate Engine.
    """
    model_config = ConfigDict(frozen=True)

    proposal_id: str
    target_entity_id: str
    proposed_status: TerminalInvestigationStatus
    justification: str
    agent_id: str
    created_at_utc: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class AuthorizedFollowUpRecord(BaseModel):
    """
    Cryptographically verifiable, immutable follow-up queue authorization record.
    Generated exclusively by the deterministic gate authority.
    """
    model_config = ConfigDict(frozen=True)

    record_id: str
    target_entity_id: str
    ra_deg: float
    dec_deg: float
    authorized_epoch_utc: str
    terminal_status: TerminalInvestigationStatus
    gate_digest_sha256: str
    authorized_priority_score: float
    gate_justifications: List[str]
    is_authoritative: bool = True


class FollowUpQueueManager:
    """
    Telescope Target-of-Opportunity (ToO) Follow-Up Queue Manager.
    Enforces a strict system boundary:
    1. Agents cannot write directly to the queue.
    2. Proposals are independently validated by the Deterministic Evidence Gate.
    3. Every queued record is sealed with an SHA-256 audit digest.
    """

    def __init__(self) -> None:
        self._queue: List[AuthorizedFollowUpRecord] = []
        self._audit_log: List[Dict[str, Any]] = []

    def direct_agent_enqueue(self, *args: Any, **kwargs: Any) -> None:
        """
        Guaranteed failure for direct agent submissions.
        Agents do not have permission to execute queue insertions.
        """
        raise UnauthorizedQueueSubmissionError(
            "Direct agent queue writes are prohibited by system boundary governance. "
            "All telescope follow-up requests must be authorized via Deterministic Evidence Gates."
        )

    @staticmethod
    def compute_gate_digest(dossier: InvestigationDossier) -> str:
        """Computes a deterministic SHA-256 digest sealing the gate outcome and candidate coordinates."""
        canonical_str = (
            f"entity:{dossier.target_entity_id}|"
            f"ra:{dossier.ra_deg:.6f}|dec:{dossier.dec_deg:.6f}|"
            f"status:{dossier.terminal_status.value}|"
            f"integrity:{dossier.gate_evaluation.data_integrity_passed}|"
            f"artifact:{dossier.gate_evaluation.artifact_filter_passed}|"
            f"physics:{dossier.gate_evaluation.physical_plausibility_passed}|"
            f"fatal_objs:{len(dossier.gate_evaluation.unresolved_fatal_objections)}"
        )
        return hashlib.sha256(canonical_str.encode("utf-8")).hexdigest()

    def authorize_and_enqueue(
        self,
        dossier: InvestigationDossier,
        independent_gate_engine: Optional[DeterministicEvidenceGateEngine] = None,
        candidate_data: Optional[Dict[str, Any]] = None,
    ) -> AuthorizedFollowUpRecord:
        """
        Validates dossier at the queue boundary and enqueues authorized follow-up requests.
        Rejects all unverified, failed, or compromised dossiers.
        """
        # Deep copy to ensure zero caller reference leakage
        dossier_safe = copy.deepcopy(dossier)

        # 1. Gate Alignment Check
        if dossier_safe.terminal_status != TerminalInvestigationStatus.CANDIDATE_REQUIRES_FOLLOWUP:
            raise GateValidationMismatchError(
                f"Cannot enqueue candidate with terminal status '{dossier_safe.terminal_status.value}'. "
                "Only 'CANDIDATE_REQUIRES_FOLLOWUP' candidates can be scheduled for telescope ToO."
            )

        gate_res = dossier_safe.gate_evaluation
        if not gate_res.data_integrity_passed:
            raise GateValidationMismatchError("Cannot enqueue: data integrity gate failed.")
        if not gate_res.artifact_filter_passed:
            raise GateValidationMismatchError("Cannot enqueue: artifact filter gate rejected candidate.")
        if not gate_res.physical_plausibility_passed:
            raise GateValidationMismatchError("Cannot enqueue: physical plausibility gate failed.")
        if len(gate_res.unresolved_fatal_objections) > 0:
            raise GateValidationMismatchError("Cannot enqueue: unresolved fatal skeptic objections present.")

        # 2. Independent Gate Re-evaluation (if gate engine and candidate data provided)
        if independent_gate_engine is not None and candidate_data is not None:
            independent_eval = independent_gate_engine.evaluate_candidate(
                entity_id=dossier_safe.target_entity_id,
                n_epochs=candidate_data.get("n_epochs", dossier_safe.data_summary.get("num_detections", 6)),
                duration_days=candidate_data.get("duration_days", dossier_safe.data_summary.get("time_baseline_days", 10.0)),
                quality_flags=candidate_data.get("quality_flags", []),
                physics_fit=candidate_data.get("physics_fit"),
                literature_citations=candidate_data.get("literature_citations", list(dossier_safe.literature_context)),
                skeptic_challenges=candidate_data.get("skeptic_challenges", list(dossier_safe.skeptic_challenges)),
                has_ivoa_provenance=candidate_data.get("has_ivoa_provenance", True),
            )
            if independent_eval.terminal_status != TerminalInvestigationStatus.CANDIDATE_REQUIRES_FOLLOWUP:
                raise GateValidationMismatchError(
                    f"Independent gate re-evaluation refused follow-up (Status: {independent_eval.terminal_status.value}). "
                    "Submitted dossier gate evaluation does not match independent verification."
                )

        # 3. Cryptographic Audit Digest
        digest = self.compute_gate_digest(dossier_safe)

        # 4. Construct Immutable Authorized Record
        record_id = f"too-auth:{dossier_safe.target_entity_id}:{int(datetime.now(timezone.utc).timestamp())}"
        record = AuthorizedFollowUpRecord(
            record_id=record_id,
            target_entity_id=dossier_safe.target_entity_id,
            ra_deg=dossier_safe.ra_deg,
            dec_deg=dossier_safe.dec_deg,
            authorized_epoch_utc=datetime.now(timezone.utc).isoformat(),
            terminal_status=dossier_safe.terminal_status,
            gate_digest_sha256=digest,
            authorized_priority_score=float(dossier_safe.physical_modeling.get("parameter_space_deviation", 1.0)),
            gate_justifications=list(gate_res.gate_justifications),
            is_authoritative=True,
        )

        self._queue.append(record)
        self._audit_log.append({
            "action": "ENQUEUE_AUTHORIZED",
            "record_id": record_id,
            "target_entity_id": dossier_safe.target_entity_id,
            "digest": digest,
            "timestamp": record.authorized_epoch_utc,
        })

        return record

    def get_queue(self) -> List[AuthorizedFollowUpRecord]:
        """Returns a copy of the active follow-up queue sorted by priority score."""
        return sorted(self._queue, key=lambda r: r.authorized_priority_score, reverse=True)

    def verify_queue_integrity(self) -> bool:
        """Verifies that all queued records maintain valid non-empty digests."""
        for rec in self._queue:
            if not rec.is_authoritative or len(rec.gate_digest_sha256) != 64:
                return False
        return True

    def clear(self) -> None:
        """Clears the active queue."""
        self._queue.clear()
