"""
ASTRAEUS Multi-Agent Runtime Contracts.
Defines typed message structures, literature citation schemas, skeptic challenge protocols,
and deterministic terminal investigation statuses.
"""

from typing import Dict, Any, List, Optional
from enum import Enum
from pydantic import BaseModel, Field

from astraeus_core.epistemic import EpistemicTier, ClaimType


class AgentRole(str, Enum):
    ORCHESTRATOR = "orchestrator"
    DATA_AGENT = "data_agent"
    LITERATURE_AGENT = "literature_agent"
    SKEPTIC_AGENT = "skeptic_agent"


class CitationEvidenceType(str, Enum):
    DIRECT_MEASUREMENT = "DIRECT_MEASUREMENT"       # Spectroscopic redshift, calibrated astrometry
    INFERRED_PROPERTY = "INFERRED_PROPERTY"         # Photometric redshift, SED-fitted stellar mass
    PROPOSED_HYPOTHESIS = "PROPOSED_HYPOTHESIS"     # Proposed physical progenitor mechanism
    CATALOG_ASSOCIATION = "CATALOG_ASSOCIATION"     # Positional cross-match in SIMBAD/NED/Gaia


class LiteratureCitation(BaseModel):
    """
    Structured scientific citation preserving evidence level, source URI, and timestamp.
    """
    citation_id: str
    bibcode_or_doi: str
    title: str
    authors: str
    publication_year: int
    source_url: str
    retrieval_timestamp_iso: str
    evidence_type: CitationEvidenceType
    relevant_excerpt: str
    is_direct_evidence: bool = Field(..., description="True if direct measurement; False if inferred or hypothesis.")


class ChallengeCategory(str, Enum):
    PSF_SHAPE_FAILURE = "PSF_SHAPE_FAILURE"                       # Elongated PSF, cosmic ray spike
    SUBTRACTION_DIPOLE_ARTIFACT = "SUBTRACTION_DIPOLE_ARTIFACT"   # Positive/negative dipole subtraction error
    STELLAR_DENSITY_BLENDING = "STELLAR_DENSITY_BLENDING"         # High local stellar density, crowded field
    UNPHYSICAL_PARAMETERS = "UNPHYSICAL_PARAMETERS"               # M_Ni > 2.5 M_sun, v_s > 0.1c
    ALTERNATIVE_EXPLANATION = "ALTERNATIVE_EXPLANATION"           # Known cataclysmic variable, AGN flare
    CADENCE_INSUFFICIENCY = "CADENCE_INSUFFICIENCY"               # < 5 epochs, no pre-explosion upper limits


class ChallengeStatus(str, Enum):
    RAISED = "RAISED"
    RESOLVED = "RESOLVED"
    FATAL_DISQUALIFICATION = "FATAL_DISQUALIFICATION"


class SkepticChallenge(BaseModel):
    """
    Structured adversarial challenge generated by SkepticValidationAgent.
    Must be grounded in empirical data or physical invariants.
    """
    challenge_id: str
    category: ChallengeCategory
    assertion: str
    evidence_data: Dict[str, Any] = Field(default_factory=dict)
    status: ChallengeStatus = ChallengeStatus.RAISED
    resolution_notes: Optional[str] = None


class TerminalInvestigationStatus(str, Enum):
    """
    Deterministic terminal status assigned by evidence gates.
    Explicitly replaces binary 'discovery=true/false' declarations.
    """
    REJECTED_AS_ARTIFACT = "REJECTED_AS_ARTIFACT"
    KNOWN_OBJECT = "KNOWN_OBJECT"
    KNOWN_CLASS_UNUSUAL = "KNOWN_CLASS_UNUSUAL"
    CANDIDATE_REQUIRES_FOLLOWUP = "CANDIDATE_REQUIRES_FOLLOWUP"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
    PROCESSING_FAILED = "PROCESSING_FAILED"


class AgentTask(BaseModel):
    """
    Task allocated by Orchestrator to specialized agents.
    """
    task_id: str
    target_entity_id: str
    assigned_role: AgentRole
    action: str
    parameters: Dict[str, Any] = Field(default_factory=dict)
    created_at_mjd: float
    completed: bool = False
    error: Optional[str] = None


class AgentMessage(BaseModel):
    """
    Epistemic-aware inter-agent message.
    """
    message_id: str
    sender_role: AgentRole
    recipient_role: AgentRole
    epistemic_tier: EpistemicTier
    claim_type: ClaimType
    content: str
    evidence_references: List[str] = Field(default_factory=list)
    attached_data: Dict[str, Any] = Field(default_factory=dict)
